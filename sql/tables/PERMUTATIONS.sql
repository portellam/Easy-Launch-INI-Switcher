CREATE TABLE "PERMUTATIONS" (
	"ID"	INTEGER,
	"FIRST_DASHBOARD_ID"	INTEGER,
	"SECOND_DASHBOARD_ID"	INTEGER,
	"CONFIGAPP_DASHBOARD_ID"	INTEGER,
	"BLOCK_XBOX_LIVE"	INTEGER NOT NULL CHECK("BLOCK_XBOX_LIVE" IN (0, 1)),
	"FIRST_PLUGIN_ID"	INTEGER,
	"SECOND_PLUGIN_ID"	INTEGER,
	"THIRD_PLUGIN_ID"	INTEGER,
	"FOURTH_PLUGIN_ID"	INTEGER,
	"FIFTH_PLUGIN_ID"	INTEGER,
	"IS_VALID"	INTEGER CHECK("IS_VALID" IN (0, 1)),
	"NOTES"	TEXT,
	PRIMARY KEY("ID") ON CONFLICT ROLLBACK,
	FOREIGN KEY("CONFIGAPP_DASHBOARD_ID") REFERENCES "DASHBOARDS"("ID"),
	FOREIGN KEY("FIFTH_PLUGIN_ID") REFERENCES "PLUGINS"("ID"),
	FOREIGN KEY("FIRST_DASHBOARD_ID") REFERENCES "DASHBOARDS"("ID"),
	FOREIGN KEY("FIRST_PLUGIN_ID") REFERENCES "PLUGINS"("ID"),
	FOREIGN KEY("FOURTH_PLUGIN_ID") REFERENCES "PLUGINS"("ID"),
	FOREIGN KEY("SECOND_DASHBOARD_ID") REFERENCES "DASHBOARDS"("ID"),
	FOREIGN KEY("SECOND_PLUGIN_ID") REFERENCES "PLUGINS"("ID"),
	FOREIGN KEY("THIRD_PLUGIN_ID") REFERENCES "PLUGINS"("ID")
) STRICT